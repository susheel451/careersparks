/**
 * scripts/build-config.mjs
 * Reads .env and writes public values to assets/js/site-config.js.
 * Run: node scripts/build-config.mjs
 *
 * SECURITY: Only CLOUDINARY_CLOUD_NAME and ENQUIRY_FORM_ENDPOINT are
 * written to the browser file. API_KEY and API_SECRET are NEVER written.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_FILE = path.join(ROOT, ".env");
const OUT_FILE = path.join(ROOT, "assets/js/site-config.js");

const env = {};
if (fs.existsSync(ENV_FILE)) {
  for (const line of fs.readFileSync(ENV_FILE, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/);
    if (m && !m[0].trimStart().startsWith("#")) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}

const publicConfig = {
  cloudinaryCloudName: env.CLOUDINARY_CLOUD_NAME || "",
  enquiryEndpoint: env.ENQUIRY_FORM_ENDPOINT || "",
};

// Verify secret is not accidentally exposed
const out = JSON.stringify(publicConfig, null, 2);
if (env.CLOUDINARY_API_SECRET && out.includes(env.CLOUDINARY_API_SECRET)) {
  console.error("SECURITY ERROR: API_SECRET would be written to the browser bundle. Aborting.");
  process.exit(1);
}

const content = `/* AUTO-GENERATED by scripts/build-config.mjs — do not edit by hand.
   Contains PUBLIC values only. Secrets are never written here. */
window.CS_CONFIG = ${out};\n`;
fs.writeFileSync(OUT_FILE, content);
console.log("✓ site-config.js written.");
if (!env.CLOUDINARY_CLOUD_NAME) console.log("  → CLOUDINARY_CLOUD_NAME is empty; images will be served from local paths.");
if (!env.ENQUIRY_FORM_ENDPOINT) console.log("  → ENQUIRY_FORM_ENDPOINT is empty; form will use SMS compose fallback.");
